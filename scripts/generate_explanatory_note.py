def configure_document(doc: Document) -> None:
    section = doc.sections[-1]
    section.top_margin = Cm(2)
    section.bottom_margin = Cm(2)
    section.left_margin = Cm(3)
    section.right_margin = Cm(1.5)

    styles = doc.styles
    normal = styles["Normal"]
    normal.font.name = "Times New Roman"
    normal._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    normal.font.size = Pt(14)
    normal.font.bold = False
    normal.font.italic = False
    normal.font.color.rgb = RGBColor(0, 0, 0)
    normal.paragraph_format.first_line_indent = Cm(1.5)
    normal.paragraph_format.line_spacing = 1.5
    normal.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    normal.paragraph_format.space_after = Pt(0)
    normal.paragraph_format.space_before = Pt(0)

    for style_name in ("Heading 1", "Heading 2", "Heading 3"):
        heading = styles[style_name]
        heading.font.name = "Times New Roman"
        heading._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
        heading.font.size = Pt(14)
        heading.font.bold = False
        heading.font.italic = False
        heading.font.color.rgb = RGBColor(0, 0, 0)
        heading.paragraph_format.first_line_indent = Cm(1.5)
        heading.paragraph_format.line_spacing = 1.5
        heading.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.LEFT
        heading.paragraph_format.space_after = Pt(0)
        heading.paragraph_format.space_before = Pt(0)


def enable_field_update_on_open(doc: Document) -> None:
    settings = doc.settings._element
    update_fields = settings.find(qn("w:updateFields"))
    if update_fields is None:
        update_fields = OxmlElement("w:updateFields")
        settings.append(update_fields)
    update_fields.set(qn("w:val"), "true")


def set_table_borders(table) -> None:
    tbl = table._tbl
    tbl_pr = tbl.tblPr
    borders = tbl_pr.first_child_found_in("w:tblBorders")
    if borders is None:
        borders = OxmlElement("w:tblBorders")
        tbl_pr.append(borders)
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        tag = "w:" + edge
        element = borders.find(qn(tag))
        if element is None:
            element = OxmlElement(tag)
            borders.append(element)
        element.set(qn("w:val"), "single")
        element.set(qn("w:sz"), "8")
        element.set(qn("w:space"), "0")
        element.set(qn("w:color"), "000000")


def add_paragraph(doc: Document, text: str = "", align=WD_ALIGN_PARAGRAPH.JUSTIFY, first=True):
    p = doc.add_paragraph()
    p.alignment = align
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_after = Pt(0)
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.first_line_indent = Cm(1.5 if first else 0)
    run = p.add_run(text)
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    run.font.size = Pt(14)
    run.bold = False
    run.italic = False
    return p


def add_center(doc: Document, text: str):
    return add_paragraph(doc, text, WD_ALIGN_PARAGRAPH.CENTER, first=False)


def add_section_heading(doc: Document, text: str):
    doc.add_page_break()
    p = add_paragraph(doc, text, WD_ALIGN_PARAGRAPH.LEFT, first=True)
    p.style = doc.styles["Heading 1"]
    return p


def add_subheading(doc: Document, text: str):
    add_paragraph(doc)
    add_paragraph(doc)
    p = add_paragraph(doc, text, WD_ALIGN_PARAGRAPH.LEFT, first=True)
    p.style = doc.styles["Heading 2"]
    add_paragraph(doc)
    return p


def add_bullets(doc: Document, items: list[str]):
    for i, item in enumerate(items):
        suffix = "." if i == len(items) - 1 else ";"
        add_paragraph(doc, "– " + item.rstrip(".;") + suffix)


def add_numbered_ru(doc: Document, items: list[str]):
    letters = ["а", "б", "в", "г", "д", "е", "ж", "з", "и", "к"]
    for i, item in enumerate(items):
        suffix = "." if i == len(items) - 1 else ";"
        add_paragraph(doc, f"{letters[i]}) {item.rstrip('.;')}{suffix}")


def add_code_lines(doc: Document, lines: list[str]) -> None:
    for line in lines:
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        p.paragraph_format.first_line_indent = Cm(0)
        p.paragraph_format.line_spacing = 1.0
        p.paragraph_format.space_after = Pt(0)
        p.paragraph_format.space_before = Pt(0)
        run = p.add_run(line)
        run.font.name = "Courier New"
        run._element.rPr.rFonts.set(qn("w:eastAsia"), "Courier New")
        run.font.size = Pt(10)
        run.bold = False
        run.italic = False


def add_table(doc: Document, title: str, headers: list[str], rows: list[list[str]]):
    add_paragraph(doc)
    add_paragraph(doc, title, WD_ALIGN_PARAGRAPH.LEFT, first=True)
    table = doc.add_table(rows=1, cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    set_table_borders(table)
    for i, header in enumerate(headers):
        cell = table.rows[0].cells[i]
        cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
        cell.text = header
    for row in rows:
        cells = table.add_row().cells
        for i, value in enumerate(row):
            cells[i].text = value
            cells[i].vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
    for row in table.rows:
        for cell in row.cells:
            for p in cell.paragraphs:
                p.alignment = WD_ALIGN_PARAGRAPH.LEFT
                p.paragraph_format.first_line_indent = Cm(0)
                p.paragraph_format.line_spacing = 1.5
                for run in p.runs:
                    run.font.name = "Times New Roman"
                    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
                    run.font.size = Pt(14)
                    run.bold = False
                    run.italic = False


def draw_box(ax, xy, text, width=2.8, height=0.8, fontsize=10):
    x, y = xy
    rect = plt.Rectangle((x, y), width, height, fill=False, linewidth=1.6)
    ax.add_patch(rect)
    ax.text(x + width / 2, y + height / 2, text, ha="center", va="center", fontsize=fontsize, wrap=True)


def arrow(ax, start, end):
    ax.annotate("", xy=end, xytext=start, arrowprops=dict(arrowstyle="->", linewidth=1.4))


