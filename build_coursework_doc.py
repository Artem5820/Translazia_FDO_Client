def set_run_font(run, size: int = 14, bold: bool | None = None) -> None:
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    run.font.size = Pt(size)
    if bold is not None:
        run.bold = bold


def configure_document(doc: Document) -> None:
    for section in doc.sections:
        section.page_width = Cm(21)
        section.page_height = Cm(29.7)
        section.left_margin = Cm(3)
        section.right_margin = Cm(1.5)
        section.top_margin = Cm(2)
        section.bottom_margin = Cm(2)

    normal = doc.styles["Normal"]
    normal.font.name = "Times New Roman"
    normal._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    normal.font.size = Pt(14)
    normal.paragraph_format.first_line_indent = Cm(1.5)
    normal.paragraph_format.line_spacing = 1.5
    normal.paragraph_format.space_after = Pt(0)

    for name in ["Heading 1", "Heading 2", "Heading 3"]:
        style = doc.styles[name]
        style.font.name = "Times New Roman"
        style._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
        style.font.size = Pt(14)
        style.font.bold = False
        style.font.color.rgb = RGBColor(0, 0, 0)
        style.paragraph_format.first_line_indent = Cm(1.5)
        style.paragraph_format.line_spacing = 1.5
        style.paragraph_format.space_before = Pt(0)
        style.paragraph_format.space_after = Pt(0)


def remove_old_body(doc: Document) -> None:
    body = doc._body._element
    start_el = None
    for para in doc.paragraphs:
        if para.text.strip() == "Введение":
            start_el = para._element
            break
    if start_el is None:
        return
    children = list(body)
    start = children.index(start_el)
    for element in children[start:]:
        if element.tag == qn("w:sectPr"):
            continue
        body.remove(element)


def replace_front_matter_topic(doc: Document) -> None:
    replacements = {
        "Разработка нейросетевого модуля видеоанализа VK-трансляций": "Разработка desktop-клиента мониторинга онлайн-трансляций ФДО",
        "учебных занятий": "с интеграцией видео- и аудиоанализа",
        "модуля видеоанализа VK-трансляций": "desktop-клиента мониторинга онлайн-трансляций",
        "нейросетевого модуля видеоанализа VK-трансляций": "desktop-клиента мониторинга онлайн-трансляций",
    }
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                for para in cell.paragraphs:
                    new_text = para.text
                    for old, new in replacements.items():
                        new_text = new_text.replace(old, new)
                    if new_text != para.text:
                        for run in list(para.runs):
                            run._element.getparent().remove(run._element)
                        run = para.add_run(new_text)
                        set_run_font(run)


def add_para(doc: Document, text: str = "", style: str = "Normal", first: bool = True):
    para = doc.add_paragraph(style=style)
    if text:
        run = para.add_run(text)
        set_run_font(run)
    para.paragraph_format.first_line_indent = Cm(1.5) if first else Cm(0)
    para.paragraph_format.line_spacing = 1.5
    para.paragraph_format.space_after = Pt(0)
    para.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    return para


def h1(doc: Document, text: str) -> None:
    add_para(doc, text, "Heading 1")


def h2(doc: Document, text: str) -> None:
    add_para(doc, text, "Heading 2")


def caption(doc: Document, text: str) -> None:
    add_para(doc, text)


def blank(doc: Document) -> None:
    para = doc.add_paragraph()
    para.paragraph_format.line_spacing = 1.5
    para.paragraph_format.space_after = Pt(0)


def add_table(doc: Document, headers: list[str], rows: list[list[str]], widths: list[float] | None = None) -> None:
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for index, value in enumerate(headers):
        table.rows[0].cells[index].text = value
    for row in rows:
        cells = table.add_row().cells
        for index, value in enumerate(row):
            cells[index].text = value

    for row_index, row in enumerate(table.rows):
        for col_index, cell in enumerate(row.cells):
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            if widths:
                cell.width = Cm(widths[col_index])
            tc_pr = cell._tc.get_or_add_tcPr()
            margins = OxmlElement("w:tcMar")
            for side in ["top", "left", "bottom", "right"]:
                margin = OxmlElement(f"w:{side}")
                margin.set(qn("w:w"), "80")
                margin.set(qn("w:type"), "dxa")
                margins.append(margin)
            tc_pr.append(margins)
            for para in cell.paragraphs:
                para.alignment = WD_ALIGN_PARAGRAPH.CENTER if row_index == 0 or col_index == 0 else WD_ALIGN_PARAGRAPH.LEFT
                para.paragraph_format.first_line_indent = Cm(0)
                para.paragraph_format.line_spacing = 1.0
                para.paragraph_format.space_after = Pt(0)
                for run in para.runs:
                    set_run_font(run, 12, bold=True if row_index == 0 else None)
    blank(doc)


def add_picture(doc: Document, path: Path, cap: str, width_cm: float) -> None:
    para = doc.add_paragraph()
    para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    para.paragraph_format.first_line_indent = Cm(0)
    run = para.add_run()
    run.add_picture(str(path), width=Cm(width_cm))
    caption(doc, cap)
    blank(doc)


